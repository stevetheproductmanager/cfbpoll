/** Best-effort fallback for a name not in the fixed table (e.g. a
 * realignment/name CFBD hasn't been mapped for yet) — lowercase, strip
 * anything that isn't a letter/number, matching the table's own convention. */
export function teamHandle(name) {
  return TEAM_HANDLES[name] || String(name || '').toLowerCase().replace(/[^a-z0-9]/g, '')
}
